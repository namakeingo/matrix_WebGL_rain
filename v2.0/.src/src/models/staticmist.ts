// The static mist's model (Feature U3, story M1; units.ui.staticmist.ts). Pure, no GL, no page, importable in any thread: the fog's two layers as functions. The BASE MIST is a noise-modulated exponential height
// layer whose density never drifts (the noise read at fixed offsets, a window normalised to mean 1 so its mean extinction at the water is its strength); the FRONT CLOUD has a two-scale height profile and a window
// without the 20% floor; the SPLIT shares today's mean extinction at the water between them.
// - totalAtWater(i): today's mean extinction per metre at the water at Fog intensity i: f (DENSITY_FULL CLOUD_WINDOW_MEAN + MIST), f = clamp(i / 101, 0, 1) (i the layer intensity; 0 and below give none)
// - splitStrengths(i, share): { base, front }: base = share total, front = (1 - share) total / FRONT_WINDOW_MEAN (the front's sigma): base + front FRONT_WINDOW_MEAN = total
// - frontWindow(n) = 0.8 smoothstep(0.4, 0.6, n); frontProfile(y, hf, t) = (1 - t) e^(-max(y, 0) / 4) + t e^(-max(y, 0) / hf); frontColumn(hf, t) = (1 - t) 4 + t hf
// - baseDensity(y, hb, base, m) = base e^(-max(y, 0) / hb) m (no time); baseNoise(p, read, lod): the three octaves (OCTAVES) read at p / size + offset at the level max(0, lod - log2(size)), mixed by their weights
// - window(n, narrow), windowMean(lod, narrow), meanOne(n, lod, narrow) = window / windowMean (mean 1 over the noise read at the lod)
// - baseDepth (M.MistBeyond.depth) and baseDepthNumeric (composite Simpson) of base e^(-y / hb) along a ray
// - coarsen(distance, focal, size) -> { lodShift, amplitude, cutoffNarrow }, resolvableDistance(focal, size), modulation(n, lod, c): the distance coarsening (focal in cells of the grid or the screen)
// - viewAccumulates(change), viewAlpha(frame), staleWeight(frames), STALE_LIMIT, converged(frames), needsDraw({ change, frames }): the following of a view change by accumulation
//
// Changelog:
// 2026-11-23: the layers start from Fog intensity 1 (no longer the air alone): layerIntensity is i / 2 (was max(1, i / 2)) and the factor i / 101 (was (i - 1) / 99).
// 2026-11-23: the calibrated defaults: layerIntensity (the single Fog intensity halved), TAIL_SHARE 0.3 and TAIL_SCALE 100 (were 0.1 and 130), WINDOW_MEAN and WINDOW_TABLE at the noise contrast 5.
// 2026-11-22: Feature U3, story M5: TAIL_FLAT, FLAT_WINDOW, flatHeight, frontDensityLod (the front's tail flat).
// 2026-11-22: Feature U3, story M4: TAIL_SHARE, TAIL_SCALE (range, CORE_SCALE), EXPIRY, clampTail, clampScale, frontDensity, expiryHeight, frontDepth.
// 2026-11-22: new (Feature U3, story M1).
import { M } from "../engine/core";
import { DENSITY_FULL, MIST } from "../materials/fog";
import { MistBeyond } from "./mistbeyond";
import { FogAccum } from "./fogaccum";

const clamp = (v: number, a: number, b: number): number => Math.min(Math.max(v, a), b);
const smooth = (lo: number, hi: number, x: number): number => {
  const t = clamp((x - lo) / (hi - lo), 0, 1);
  return t * t * (3 - 2 * t);
};

// E[smoothstep(0.4, 0.6, n)] over the three-octave mix n = 0.55 a + 0.3 b + 0.15 c of three independent reads of the noise field (the exact convolution of its 8-bit histogram at NOISE_CONTRAST 5: 0.49652; 0.49676 at the earlier 10)
const WINDOW_MEAN = 0.4965;
// the front window's mean (no floor) and today's cloud window's (with its 20% floor)
const FRONT_WINDOW_MEAN = 0.8 * WINDOW_MEAN;
const CLOUD_WINDOW_MEAN = 0.2 + FRONT_WINDOW_MEAN;
// the octaves of the base mist's noise: the sizes (m), weights and FIXED offsets (texture units; no time term; distinct from the cloud's and the colour's)
const OCTAVES = [
  { size: 24, weight: 0.55, offset: [0.61, 0.23, 0.37] },
  { size: 10, weight: 0.3, offset: [0.83, 0.47, 0.19] },
  { size: 4, weight: 0.15, offset: [0.29, 0.71, 0.53] },
];
// the correlation length of the noise mix (3.8 cells x (0.55 x 24 + 0.3 x 10 + 0.15 x 4) / 128 = 0.50 m), the feature size the coarsening is measured in
const FEATURE_SIZE = 0.5;
// the share of the volume held before a view change below which the accumulation stops (one 8-bit level)
const STALE_LIMIT = 1 / 256;

// E[window(n, narrow)] over the mix read at the lod L (rows 0..10) for narrow 0, 0.25, 0.5, 0.75, 1 (columns): the window's edges at narrow c are 0.4 - 0.1 c and 0.6 - 0.2 c. Generated by Monte Carlo (400000
// positions per row, the three octaves read independently at the mip level max(0, L - log2(size)), the levels' blend for a fraction) over the generator's field (units.ui.mistalbedo.ts's twin) at
// NOISE_CONTRAST 5 (stretch 60) by .assets/matrix_web_3d_rain/windowtable/windowtable.mjs (seed 20261123); [0][0] is the exact WINDOW_MEAN. Another contrast needs another table (the script takes the stretch).
const WINDOW_TABLE = [
  [0.4965, 0.5408, 0.5864, 0.6341, 0.6797],
  [0.4965, 0.5405, 0.5857, 0.6332, 0.6787],
  [0.4962, 0.5403, 0.5856, 0.6328, 0.6783],
  [0.4971, 0.5397, 0.5844, 0.633, 0.6819],
  [0.4964, 0.5345, 0.5758, 0.6238, 0.6778],
  [0.4968, 0.5373, 0.5792, 0.6258, 0.6804],
  [0.494, 0.5548, 0.6168, 0.6811, 0.7488],
  [0.4931, 0.6104, 0.7232, 0.8251, 0.9088],
  [0.4866, 0.7034, 0.8797, 0.9709, 0.9967],
  [0.4825, 0.7648, 0.967, 0.9996, 1],
  [0.4815, 0.7813, 0.9932, 1, 1],
];

const factor = (i: number): number => clamp(i / 101, 0, 1);

// the single Fog intensity as the two layers get it: halved (no floor), then the i / 101 mapping: Fog 40 is the layer 20, Fog 100 the layer 50, Fog 1 the layer 0.5 (a cloud already at the slider's minimum); a test's 0 is none
const layerIntensity = (i: number): number => i / 2;

function totalAtWater(i: number): number {
  return factor(i) * (DENSITY_FULL * CLOUD_WINDOW_MEAN + MIST);
}

function splitStrengths(i: number, share: number): { base: number; front: number } {
  const s = clamp(share, 0, 1), total = totalAtWater(i);
  return { base: s * total, front: ((1 - s) * total) / FRONT_WINDOW_MEAN };
}

const frontWindow = (n: number): number => 0.8 * smooth(0.4, 0.6, n);

function frontProfile(y: number, hf: number, t: number): number {
  const a = Math.max(y, 0);
  return (1 - t) * Math.exp(-a / 4) + t * Math.exp(-a / hf);
}

const frontColumn = (hf: number, t: number): number => (1 - t) * 4 + t * hf;

// the front's two-scale profile parameters (Feature U3, story M4): the tail's share and scale (shipped defaults, the scale's range) and the density's cut-off per metre (the shaders' 1e-5)
const TAIL_SHARE = 0.3;
const TAIL_SCALE = 100;
const TAIL_SCALE_MIN = 4;
const TAIL_SCALE_MAX = 130;
const CORE_SCALE = 4;
const EXPIRY = 1e-5;
const clampTail = (t: number): number => (typeof t === "number" && !isNaN(t) ? clamp(t, 0, 1) : TAIL_SHARE);
const clampScale = (hf: number): number => (typeof hf === "number" && !isNaN(hf) ? clamp(hf, TAIL_SCALE_MIN, TAIL_SCALE_MAX) : TAIL_SCALE);

// the front's density at height y with the noise n: none where sigma x profile is under EXPIRY (the shader's density())
function frontDensity(sigma: number, y: number, n: number, hf: number, t: number): number {
  const scale = sigma * frontProfile(y, hf, t);
  return scale < EXPIRY ? 0 : scale * frontWindow(n);
}

// the front's tail flat (Feature U3, story M5): where sigma x profile is under TAIL_FLAT per metre the noise is replaced by its window's mean FLAT_WINDOW (0.4 = frontWindow(0.5)); the error is at most 0.4 TAIL_FLAT
// per metre. flat 0 is no replacement (lod off)
const TAIL_FLAT = 0.002;
const FLAT_WINDOW = 0.4;

function frontDensityLod(sigma: number, y: number, n: number, hf: number, t: number, flat: number): number {
  const scale = sigma * frontProfile(y, hf, t);
  if (scale < EXPIRY) return 0;
  return scale < flat ? scale * FLAT_WINDOW : scale * frontWindow(n);
}

// the greatest height at which sigma x profile is still at least `flat` (0 where sigma is under it; Infinity for no flat)
function flatHeight(sigma: number, hf: number, t: number, flat: number): number {
  if (!(flat > 0)) return Infinity;
  if (sigma < flat) return 0;
  let lo = 0, hi = 1;
  while (sigma * frontProfile(hi, hf, t) >= flat && hi < 1e7) hi *= 2;
  for (let i = 0; i < 200 && hi - lo > 1e-9 * hi; i++) {
    const mid = 0.5 * (lo + hi);
    if (sigma * frontProfile(mid, hf, t) >= flat) lo = mid;
    else hi = mid;
  }
  return lo;
}

// the greatest height at which sigma x profile is still at least EXPIRY (the profile never rises: bisection), 0 where sigma is under it
function expiryHeight(sigma: number, hf: number, t: number): number {
  if (sigma < EXPIRY) return 0;
  let lo = 0, hi = 1;
  while (sigma * frontProfile(hi, hf, t) >= EXPIRY && hi < 1e7) hi *= 2;
  for (let i = 0; i < 200 && hi - lo > 1e-9 * hi; i++) {
    const mid = 0.5 * (lo + hi);
    if (sigma * frontProfile(mid, hf, t) >= EXPIRY) lo = mid;
    else hi = mid;
  }
  return lo;
}

const baseDensity = (y: number, hb: number, base: number, m: number): number => base * Math.exp(-Math.max(y, 0) / hb) * m;

function baseNoise(p: number[], read: (q: number[], lod: number) => number, lod = 0): number {
  let n = 0;
  for (const o of OCTAVES) n += o.weight * read([p[0]! / o.size + o.offset[0]!, p[1]! / o.size + o.offset[1]!, p[2]! / o.size + o.offset[2]!], Math.max(0, lod - Math.log2(o.size)));
  return n;
}

// baseNoise at (x, y, z) read by a scalar reader read3(x, y, z, level): the same octaves and arithmetic without the arrays (the base mist job's, called once for each gather of a slice that is not flat)
function baseNoiseXYZ(x: number, y: number, z: number, read3: (x: number, y: number, z: number, lod: number) => number, lod = 0): number {
  let n = 0;
  for (let i = 0; i < OCTAVES.length; i++) {
    const o = OCTAVES[i]!;
    n += o.weight * read3(x / o.size + o.offset[0]!, y / o.size + o.offset[1]!, z / o.size + o.offset[2]!, Math.max(0, lod - Math.log2(o.size)));
  }
  return n;
}

function windowAt(n: number, narrow = 0): number {
  return smooth(0.4 - 0.1 * narrow, 0.6 - 0.2 * narrow, n);
}

function windowMean(lod: number, narrow = 0): number {
  const l = clamp(lod, 0, 10), c = clamp(narrow, 0, 1) * 4, l0 = Math.min(Math.floor(l), 9), c0 = Math.min(Math.floor(c), 3), fl = l - l0, fc = c - c0;
  const at = (a: number, b: number): number => WINDOW_TABLE[a]![b]!;
  return (1 - fl) * ((1 - fc) * at(l0, c0) + fc * at(l0, c0 + 1)) + fl * ((1 - fc) * at(l0 + 1, c0) + fc * at(l0 + 1, c0 + 1));
}

const meanOne = (n: number, lod = 0, narrow = 0): number => windowAt(n, narrow) / windowMean(lod, narrow);

function baseDepth(base: number, hb: number, eyeY: number, slope: number, from: number, to: number): number {
  return MistBeyond.depth(base, hb, eyeY, slope, from, to);
}

// the closed form of the profile's integral along a ray from the eye, from..to
function frontDepth(eyeY: number, slope: number, hf: number, t: number, from: number, to: number): number {
  return (1 - t) * layerDepth(CORE_SCALE, eyeY, slope, from, to) + t * layerDepth(hf, eyeY, slope, from, to);
}

// the integral of e^(-max(y, 0) / h) along the ray y = eyeY + slope s over from..to: a stretch above the water is len e^(-y0 / h) (1 - e^(-x)) / x, x = (y1 - y0) / h (the series limit len e^(-y0 / h) for a level stretch),
// a stretch under it is its length; the ray's crossing of the water splits the range
function layerDepth(h: number, eyeY: number, slope: number, from: number, to: number): number {
  const stretch = (s0: number, s1: number): number => {
    const y0 = eyeY + slope * s0, y1 = eyeY + slope * s1, len = s1 - s0;
    if (y0 <= 0 && y1 <= 0) return len;
    const x = (Math.max(y1, 0) - Math.max(y0, 0)) / h;
    return len * Math.exp(-Math.max(y0, 0) / h) * (Math.abs(x) < 1e-9 ? 1 : -Math.expm1(-x) / x);
  };
  if (to <= from) return 0;
  const cross = slope !== 0 ? -eyeY / slope : Infinity;
  return cross > from && cross < to ? stretch(from, cross) + stretch(cross, to) : stretch(from, to);
}

function baseDepthNumeric(base: number, hb: number, eyeY: number, slope: number, from: number, to: number, steps = 2000): number {
  const h = (to - from) / steps;
  let s = 0;
  for (let k = 0; k <= steps; k++) s += (k === 0 || k === steps ? 1 : k % 2 ? 4 : 2) * base * Math.exp(-Math.max(eyeY + slope * (from + k * h), 0) / hb);
  return (s * h) / 3;
}

interface Coarse {
  lodShift: number;
  amplitude: number;
  cutoffNarrow: number;
}

// r = distance / (focal size): the pixel (or cell) footprint over the feature size; a focal or size of 0 is unresolvable at any distance above 0
function coarsen(distance: number, focal: number, size = FEATURE_SIZE): Coarse {
  const r = focal > 0 && size > 0 ? Math.max(distance, 0) / (focal * size) : distance > 0 ? Infinity : 0;
  return { lodShift: r <= 0.25 ? 0 : Math.min(10, Math.log2(r / 0.25)), amplitude: 1 - smooth(0.5, 2, r), cutoffNarrow: smooth(0.25, 1, r) };
}

const resolvableDistance = (focal: number, size = FEATURE_SIZE): number => 2 * focal * size;

const modulation = (n: number, lod: number, c: Coarse): number => 1 + c.amplitude * (meanOne(n, lod, c.cutoffNarrow) - 1);

const viewAccumulates = (change: string): boolean => change === "view";
const viewAlpha = (frame: number): number => FogAccum.alpha(frame + 1, FogAccum.FRAMES);
function staleWeight(frames: number): number {
  let w = 1;
  for (let f = 0; f < frames; f++) w *= 1 - viewAlpha(f);
  return w;
}
const converged = (frames: number): boolean => staleWeight(frames) < STALE_LIMIT;
function needsDraw(state: { change: string; frames: number }): boolean {
  if (state.change === "view") return !converged(state.frames);
  return (state.change === "settings" || state.change === "size") && state.frames < 1;
}

